export type AccountCopy = (typeof accountTranslations)[Language];

export function formatCopy(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ''));
}

/** Maps a shared API error envelope (or a network failure) to a localized message. */
export function accountErrorMessage(error: unknown, language: Language): string {
  const copy = accountTranslations[language].errors;
  const data = (error as { data?: unknown } | null)?.data;
  if (data && typeof data === 'object') {
    const messageKey = (data as { messageKey?: unknown }).messageKey;
    if (typeof messageKey === 'string' && messageKey in copy) {
      return copy[messageKey as keyof typeof copy];
    }
  }
  const status = (error as { status?: unknown } | null)?.status;
  if (typeof status !== 'number' || status === 0) return copy.network;
  return copy.fallback;
}

